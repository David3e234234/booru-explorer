// Client-side i18n. Russian is the source language: it lives in the markup
// (data-i18n* fallbacks) and in JS call sites as the t() fallback argument.
// The English dictionary overrides those strings at runtime.

const LANG_KEY = 'booru_lang';

let currentLang = 'ru';
try {
  if (localStorage.getItem(LANG_KEY) === 'en') currentLang = 'en';
} catch {}

const en = {};

export function getLang() {
  return currentLang;
}

// t('ns.key', 'Русский текст') -> English dict value or the Russian fallback
export function t(key, fallback = '') {
  if (currentLang === 'en') {
    return Object.prototype.hasOwnProperty.call(en, key) ? en[key] : (fallback || key);
  }
  return fallback || key;
}

export function setLang(lang) {
  const next = lang === 'en' ? 'en' : 'ru';
  if (next === currentLang) return;
  currentLang = next;
  try { localStorage.setItem(LANG_KEY, next); } catch {}
  applyStaticTranslations();
  document.dispatchEvent(new CustomEvent('booru:langchange', { detail: { lang: next } }));
}

function applyAttr(el, attr, key) {
  // Keep the original Russian value on first touch so switching back works
  if (!el.dataset[attr + 'Ru']) el.dataset[attr + 'Ru'] = el[attr] || '';
  const fallback = el.dataset[attr + 'Ru'];
  el[attr] = currentLang === 'en' ? t(key, fallback) : fallback;
}

// Swaps text/title/placeholder for every marked element under root
export function applyStaticTranslations(root = document) {
  document.documentElement.lang = currentLang;
  document.documentElement.dataset.lang = currentLang;

  root.querySelectorAll('[data-i18n]').forEach(el => {
    if (!el.dataset.i18nRu) el.dataset.i18nRu = el.textContent;
    el.textContent = currentLang === 'en' ? t(el.dataset.i18n, el.dataset.i18nRu) : el.dataset.i18nRu;
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => applyAttr(el, 'placeholder', el.dataset.i18nPlaceholder));
  root.querySelectorAll('[data-i18n-title]').forEach(el => applyAttr(el, 'title', el.dataset.i18nTitle));

  const title = root.querySelector('title[data-i18n]');
  if (title) document.title = currentLang === 'en' ? t(title.dataset.i18n, title.dataset.i18nRu || title.textContent) : (title.dataset.i18nRu || title.textContent);
}

